export function suggestIcon(name: string, issuer?: string): string {
  const lookup = (s: string) => {
    const normalized = s.toLowerCase().replace(/[^a-z0-9]/g, "")
    return APP_ICONS[normalized] || null
  }

  if (issuer) {
    const icon = lookup(issuer)
    if (icon) return icon
  }

  return lookup(name) || "Shield02Icon"
}
